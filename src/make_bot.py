"""Builds bot/src/menu.gen.js for the Telegram bot from the same menu_data.py the site uses,
and JPEG copies of dish photos for Telegram (../assets/menu/tg/<id>.jpg on the site; Telegram is unreliable with WebP by URL).
Never edit menu.gen.js by hand: change menu_data.py and run src/build.sh."""
import json, pathlib
from menu_data import CATS, UNITS, ITEMS

HIDDEN = {"Куртоба"}  # keep in sync with build.py and make_worker.py
ROOT = pathlib.Path(__file__).parent
MENU_DIR = ROOT / "assets" / "menu"
TG_DIR = ROOT.parent / "assets" / "menu" / "tg"  # published straight to the site root (GitHub Pages)

items, ai_lines = [], []
for cid, c_uz, c_ru, c_en in CATS:
    rows = [r for r in ITEMS if r[1] == cid and r[3] not in HIDDEN]
    if not rows: continue
    ai_lines.append(f"#{c_ru}")
    for (sid, cat, n_uz, n_ru, n_en, d_uz, d_ru, d_en, price, unit, ph) in rows:
        photo = bool(ph) and (MENU_DIR / f"{sid}.webp").exists()
        u = UNITS.get(unit, ("", "", ""))
        items.append({"id": sid, "cat": cat, "n": [n_ru, n_uz, n_en], "d": [d_ru, d_uz, d_en], "p": price,
                      "u": [u[1], u[0], u[2]], "ph": photo})  # every text list is [ru, uz, en]
        if price is not None:  # the AI only sees dishes that can be ordered
            ai_lines.append(f"{n_ru}/{n_uz}|{price // 1000}к" + (f"|{d_ru[:48]}" if d_ru else ""))
noprice = [r[3] for r in ITEMS if r[8] is None and r[3] not in HIDDEN]
cats = [{"id": c[0], "n": [c[2], c[1], c[3]]} for c in CATS if any(i["cat"] == c[0] for i in items)]

js = "// GENERATED by src/make_bot.py from src/menu_data.py — do not edit\n"
js += "export const CATS = " + json.dumps(cats, ensure_ascii=False) + ";\n"
js += "export const ITEMS = " + json.dumps(items, ensure_ascii=False) + ";\n"
js += "export const AI_MENU = " + json.dumps("\n".join(ai_lines), ensure_ascii=False) + ";\n"
js += "export const AI_NOPRICE = " + json.dumps(", ".join(noprice), ensure_ascii=False) + ";\n"
out = ROOT.parent / "bot" / "src" / "menu.gen.js"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(js, encoding="utf-8")

# JPEG copies for Telegram (only rebuilt when the WebP is newer)
try:
    from PIL import Image
    TG_DIR.mkdir(parents=True, exist_ok=True)
    n = 0
    for it in items:
        if not it["ph"]: continue
        src, dst = MENU_DIR / f"{it['id']}.webp", TG_DIR / f"{it['id']}.jpg"
        if dst.exists() and dst.stat().st_mtime >= src.stat().st_mtime: continue
        Image.open(src).convert("RGB").save(dst, "JPEG", quality=74, optimize=True, progressive=True); n += 1
    print(f"menu.gen.js: {len(items)} dishes, {n} new tg jpgs")
except ImportError:
    print("menu.gen.js written; Pillow missing, tg jpgs skipped (pip install pillow)")
